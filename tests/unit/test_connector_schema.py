from textwrap import dedent

import pytest
from pydantic import ValidationError

from connic import cli
from connic.connector_schema import ConnectorFile
from connic.loader import ProjectLoader


def write_file(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(dedent(content).strip() + "\n")


def write_agents(project):
    write_file(
        project / "agents" / "order-processor.yaml",
        """
        version: "1.0"
        name: order-processor
        description: Processes order events
        model: openai/gpt-4o
        system_prompt: Process the order.
        """,
    )
    write_file(
        project / "agents" / "audit-logger.yaml",
        """
        version: "1.0"
        name: audit-logger
        description: Logs audit events
        model: openai/gpt-4o
        system_prompt: Log the event.
        """,
    )
    write_file(
        project / "agents" / "phone-agent.yaml",
        """
        version: "1.0"
        name: phone-agent
        description: Answers calls
        model: gemini/gemini-3.1-flash-live-preview
        system_prompt: Help the caller.
        voice_config:
          voice: Kore
        """,
    )


def load(project):
    loader = ProjectLoader(str(project), validation_only=True)
    connectors = loader.load_connectors(loader.load_agents())
    return connectors, loader._load_errors


def connector(**data):
    return ConnectorFile.model_validate({"key": "order-events", **data})


def test_loads_connector_with_environment_overrides(tmp_path):
    write_agents(tmp_path)
    write_file(
        tmp_path / "connectors" / "order-events.yaml",
        """
        type: kafka
        mode: inbound
        connection: orders-kafka-staging
        bridge: staging-cluster
        config:
          topic: ${ORDER_EVENTS_TOPIC}
          auto_offset_reset: latest
        agents:
          - order-processor
          - name: audit-logger
            files_required: true
        environments:
          Staging:
          Production:
            name: Order events (prod)
            connection: orders-kafka-prod
            config:
              group_id: connic-orders-prod
        """,
    )

    connectors, errors = load(tmp_path)

    assert errors == []
    order_events = connectors["order-events"]
    staging = order_events.for_environment("Staging")
    assert staging["name"] == "order-events"
    assert staging["connection"] == "orders-kafka-staging"
    assert staging["bridge"] == "staging-cluster"
    assert staging["config"] == {"topic": "${ORDER_EVENTS_TOPIC}", "auto_offset_reset": "latest"}
    assert [(link.name, link.files_required) for link in staging["agents"]] == [
        ("order-processor", False),
        ("audit-logger", True),
    ]
    production = order_events.for_environment("Production")
    assert production["name"] == "Order events (prod)"
    assert production["connection"] == "orders-kafka-prod"
    assert production["bridge"] == "staging-cluster"
    assert production["config"] == {
        "topic": "${ORDER_EVENTS_TOPIC}",
        "auto_offset_reset": "latest",
        "group_id": "connic-orders-prod",
    }
    assert order_events.for_environment("Development") is None


def test_connector_without_environments_deploys_everywhere_with_defaults():
    webhook = connector(type="webhook", mode="sync", agents=["order-processor"])

    assert webhook.type == "http"
    assert webhook.for_environment("Production")["name"] == "order-events"
    assert connector(type="cron", agents=["order-processor"]).mode == "inbound"


def test_outbound_link_settings():
    outbound = connector(
        type="kafka",
        mode="outbound",
        connection="orders-kafka",
        agents=[
            {"name": "order-processor", "outbound": {"usage": "middleware", "action_name": "publish_order"}},
            {"name": "audit-logger", "outbound": {"usage": "automatic", "source": ["order-events"]}},
        ],
    )

    links = outbound.for_environment("Production")["agents"]
    assert links[0].outbound.action_name == "publish_order"
    assert links[1].outbound.source == ["order-events"]


@pytest.mark.parametrize(
    "data,message",
    [
        ({"type": "slack", "mode": "inbound"}, "Slack connectors can't be declared in code"),
        ({"type": "discord"}, "unknown connector type 'discord'"),
        ({"type": "kafka", "connection": "orders-kafka"}, "mode is required for kafka connectors"),
        ({"type": "cron", "mode": "outbound"}, "cron connectors support mode inbound, not 'outbound'"),
        ({"type": "webhook", "mode": "sync", "config": {"secret": "abc"}}, "config.secret is generated by connic"),
        ({"type": "kafka", "mode": "inbound", "connection": "orders-kafka", "config": {"bridge_id": "b"}},
         "config.bridge_id isn't allowed; use bridge instead"),
        ({"type": "cron", "config": {"_pause_reason": "x"}}, "config._pause_reason is reserved for connic"),
        ({"type": "kafka", "mode": "inbound"}, "kafka connectors need a connection"),
        ({"type": "cron", "connection": "orders-kafka"}, "cron connectors don't use a connection"),
        ({"type": "cron", "bridge": "cluster"}, "cron connectors don't support a bridge"),
        ({"type": "cron", "domain": "hooks.example.com"}, "cron connectors don't support a custom domain"),
        ({"type": "cron", "config": {"prompt": "${context.user}"}}, "is not a variable reference"),
        ({"type": "cron", "config": {"prompt": "${TOPIC"}}, "unterminated '${' variable reference"),
        ({"type": "cron", "name": "Orders ${ENV}"}, "name can't use ${...}"),
        ({"type": "webhook", "mode": "sync", "agents": []}, "link at least one agent"),
        ({"type": "webhook", "mode": "sync", "agents": ["order-processor", "order-processor"]},
         "agent 'order-processor' is linked twice"),
        ({"type": "webhook", "mode": "sync",
          "agents": [{"name": "order-processor", "outbound": {"usage": "automatic"}}]},
         "outbound settings need an outbound connector"),
        ({"type": "webhook", "mode": "outbound",
          "agents": [{"name": "order-processor", "outbound": {"usage": "middleware"}}]},
         "action_name must start with a lowercase letter"),
        ({"type": "cron", "environments": {}}, "environments must list at least one environment"),
        ({"type": "cron", "schedule": "* * * * *"}, "Extra inputs are not permitted"),
    ],
)
def test_rejects_invalid_connector(data, message):
    data.setdefault("agents", ["order-processor"])

    with pytest.raises(ValidationError) as exc_info:
        connector(**data)

    assert message in str(exc_info.value)


def test_environment_override_is_validated():
    with pytest.raises(ValidationError) as exc_info:
        connector(
            type="kafka",
            mode="inbound",
            connection="orders-kafka",
            agents=["order-processor"],
            environments={"Production": {"config": {"connection_id": "abc"}}},
        )

    assert "environment 'Production': config.connection_id isn't allowed; use connection instead" in str(
        exc_info.value
    )


@pytest.mark.parametrize(
    "config,agents,message",
    [
        ({}, ["phone-agent"], "config.phone_number is required"),
        ({"phone_number": "030123456"}, ["phone-agent"], "must be in E.164 format"),
        ({"phone_number_sid": "PN123", "phone_number": "+4930123456"}, ["phone-agent"],
         "config.phone_number_sid isn't allowed; use config.phone_number instead"),
        ({"phone_number": "+4930123456"}, ["phone-agent", "order-processor"],
         "twilio connectors link exactly one voice agent"),
    ],
)
def test_rejects_invalid_voice_connector(config, agents, message):
    with pytest.raises(ValidationError) as exc_info:
        connector(type="twilio", connection="twilio-main", config=config, agents=agents)

    assert message in str(exc_info.value)


