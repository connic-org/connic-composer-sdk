def write_file(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(dedent(content).strip() + "\n")


def write_agents(project):
    write_file(
        project / "agents" / "order-processor.yaml",
        """
        version: "1.0"
        name: order-processor
        description: Processes order events
        model: openai/gpt-4o
        system_prompt: Process the order.
        """,
    )
    write_file(
        project / "agents" / "audit-logger.yaml",
        """
        version: "1.0"
        name: audit-logger
        description: Logs audit events
        model: openai/gpt-4o
        system_prompt: Log the event.
        """,
    )
    write_file(
        project / "agents" / "phone-agent.yaml",
        """
        version: "1.0"
        name: phone-agent
        description: Answers calls
        model: gemini/gemini-3.1-flash-live-preview
        system_prompt: Help the caller.
        voice_config:
          voice: Kore
        """,
    )


def load(project):
    loader = ProjectLoader(str(project), validation_only=True)
    connectors = loader.load_connectors(loader.load_agents())
    return connectors, loader._load_errors


def connector(**data):
    return ConnectorFile.model_validate({"key": "order-events", **data})


def test_loads_connector_with_environment_overrides(tmp_path):
    write_agents(tmp_path)
    write_file(
        tmp_path / "connectors" / "order-events.yaml",
        """
        type: kafka
        mode: inbound
        connection: orders-kafka-staging
        bridge: staging-cluster
        config:
          topic: ${ORDER_EVENTS_TOPIC}
          auto_offset_reset: latest
        agents:
          - order-processor
          - name: audit-logger
            files_required: true
        environments:
          Staging:
          Production:
            name: Order events (prod)
            connection: orders-kafka-prod
            config:
              group_id: connic-orders-prod
        """,
    )

    connectors, errors = load(tmp_path)

    assert errors == []
    order_events = connectors["order-events"]
    staging = order_events.for_environment("Staging")
    assert staging["name"] == "order-events"
    assert staging["connection"] == "orders-kafka-staging"
    assert staging["bridge"] == "staging-cluster"
    assert staging["config"] == {"topic": "${ORDER_EVENTS_TOPIC}", "auto_offset_reset": "latest"}
    assert [(link.name, link.files_required) for link in staging["agents"]] == [
        ("order-processor", False),
        ("audit-logger", True),
    ]
    production = order_events.for_environment("Production")
    assert production["name"] == "Order events (prod)"
    assert production["connection"] == "orders-kafka-prod"
    assert production["bridge"] == "staging-cluster"
    assert production["config"] == {
        "topic": "${ORDER_EVENTS_TOPIC}",
        "auto_offset_reset": "latest",
        "group_id": "connic-orders-prod",
    }
    assert order_events.for_environment("Development") is None


def test_connector_without_environments_deploys_everywhere_with_defaults():
    webhook = connector(type="webhook", mode="sync", agents=["order-processor"])

    assert webhook.type == "http"
