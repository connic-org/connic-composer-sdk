def test_lint_lists_connectors_and_reports_errors(tmp_path, capsys):
    write_agents(tmp_path)
    write_file(
        tmp_path / "connectors" / "order-events.yaml",
        """
        type: kafka
        mode: inbound
        connection: orders-kafka
        config:
          topic: orders
        agents: [order-processor, audit-logger]
        environments:
          Staging: {}
          Production: {}
        """,
    )

    assert cli._run_lint(project_root=str(tmp_path)) is True
    output = capsys.readouterr().out
    assert "1 connector(s) loaded" in output
    assert "order-events: kafka (inbound) → audit-logger, order-processor [Staging, Production]" in output

    assert cli._run_lint(quiet=True, project_root=str(tmp_path)) is True
    assert (
        "Lint passed: 3 agent(s) validated (audit-logger, order-processor, phone-agent), 1 connector(s)"
        in capsys.readouterr().out
    )

    write_file(tmp_path / "connectors" / "nightly.yaml", "type: cron\nconfig: {schedule: '0 2 * * *'}\nagents: [missing-agent]")

    assert cli._run_lint(quiet=True, project_root=str(tmp_path)) is False
    assert "connectors/nightly.yaml: agent 'missing-agent' doesn't exist in agents/" in capsys.readouterr().err
