def test_loader_checks_links_names_and_file_layout(tmp_path):
    write_agents(tmp_path)
    write_file(
        tmp_path / "connectors" / "hotline.yaml",
        """
        type: twilio
        connection: twilio-main
        config:
          phone_number: "+4930123456"
        agents:
          - order-processor
        """,
    )
    write_file(
        tmp_path / "connectors" / "results.yaml",
        """
        type: webhook
        mode: outbound
        name: hotline
        config:
          outbound_url: https://example.com/results
        agents:
          - name: missing-agent
            outbound:
              usage: automatic
              source: [unknown-source]
        environments:
          Production: {}
        """,
    )
    write_file(tmp_path / "connectors" / "legacy.yml", "type: cron")
    write_file(tmp_path / "connectors" / "nested" / "orders.yaml", "type: cron")
    write_file(tmp_path / "connectors" / "broken.yaml", "key: other\ntype: cron")

    connectors, errors = load(tmp_path)

    assert sorted(connectors) == ["hotline", "results"]
    assert errors == [
        "Failed to load connector: connectors/broken.yaml: 'key' comes from the file name and can't be set in the file",
        "connectors/legacy.yml: connector files must use the .yaml extension",
        "connectors/nested/orders.yaml: connector files must be directly inside connectors/",
        "connectors/hotline.yaml: agent 'order-processor' needs voice_config to answer calls",
        "connectors/results.yaml (environment 'Production'): agent 'missing-agent' doesn't exist in agents/",
        "connectors/results.yaml (environment 'Production'): outbound source 'unknown-source' isn't a connector "
        "in connectors/",
        "connectors/results.yaml (environment 'Production'): connector name 'hotline' is also used by "
        "connectors/hotline.yaml",
    ]


def test_connector_names_may_repeat_across_separate_environments(tmp_path):
    write_agents(tmp_path)
    for key, environment in (("orders-staging", "Staging"), ("orders-production", "Production")):
        write_file(
            tmp_path / "connectors" / f"{key}.yaml",
            f"""
            type: cron
            name: Nightly orders
            agents: [order-processor]
            environments:
              {environment}: {{}}
            """,
        )

    connectors, errors = load(tmp_path)

    assert errors == []
    assert sorted(connectors) == ["orders-production", "orders-staging"]


def test_lint_lists_connectors_and_reports_errors(tmp_path, capsys):
    write_agents(tmp_path)
    write_file(
        tmp_path / "connectors" / "order-events.yaml",
        """
        type: kafka
        mode: inbound
        connection: orders-kafka
        agents: [order-processor, audit-logger]
        environments:
          Staging: {}
          Production: {}
        """,
    )

    assert cli._run_lint(project_root=str(tmp_path)) is True
    output = capsys.readouterr().out
    assert "1 connector(s) loaded" in output
    assert "order-events: kafka (inbound) → audit-logger, order-processor [Staging, Production]" in output

    assert cli._run_lint(quiet=True, project_root=str(tmp_path)) is True
    assert (
        "Lint passed: 3 agent(s) validated (audit-logger, order-processor, phone-agent), 1 connector(s)"
        in capsys.readouterr().out
    )

    write_file(tmp_path / "connectors" / "nightly.yaml", "type: cron\nagents: [missing-agent]")

    assert cli._run_lint(quiet=True, project_root=str(tmp_path)) is False
    assert "connectors/nightly.yaml: agent 'missing-agent' doesn't exist in agents/" in capsys.readouterr().err
